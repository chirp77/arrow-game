# ---------------------------------------------------------------------------
# DFS 回溯求解器（仅用于关卡验证与测试，游戏运行时不用）
# ---------------------------------------------------------------------------
def solve_level(grid) -> list | None:
    """求一个合法通关序列：返回 [(r, c), ...] 点击坐标列表，无解返回 None。

    回溯思想：每步枚举"当前所有前方畅通"的箭头逐一尝试消除，
    消除后递归求解剩余盘面；走不通则恢复该箭头换下一个分支。
    每次递归箭头数减 1，深度有限，不会死循环。
    """
    g = [list(row) for row in grid]

    def dfs():
        # 当前所有箭头位置
        arrows = [
            (r, c)
            for r, row in enumerate(g)
            for c, ch in enumerate(row)
            if ch != EMPTY
        ]
        if not arrows:
            return []  # 盘面已空，找到解
        for r, c in arrows:
            if not has_clear_path(g, r, c):
                continue  # 被阻挡的箭头当前不能消除
            ch = g[r][c]
            g[r][c] = EMPTY
            result = dfs()
            if result is not None:
                return [(r, c)] + result
            g[r][c] = ch  # 回溯：恢复箭头，尝试其他分支
        return None

    return dfs()


