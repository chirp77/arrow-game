    # 开发/验证入口：打印各关是否有解及一个合法点击序列
    for i, lv in enumerate(LEVELS, 1):
        grid = lv["grid"]
        arrows = sum(ch != EMPTY for row in grid for ch in row)
        solution = solve_level(grid)
        if solution is None:
            print(f"第 {i} 关「{lv['name']}」({arrows} 箭)：无解！")
            continue
        seq = " -> ".join(f"({r},{c})[{grid[r][c]}]" for r, c in solution)
        print(f"第 {i} 关「{lv['name']}」({arrows} 箭)：有解，共 {len(solution)} 步")
        print(f"    {seq}")
